/**
 * Ranked search: number-prefix matches first, then number containment,
 * then name matches. Returns at most `limit` results.
 */
export function searchTrains(query: string, limit = 8): Train[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const digits = q.replace(/\D/g, "");
  const scored: Array<{ t: Train; rank: number }> = [];
  for (const t of TRAINS) {
    const name = t.name.toLowerCase();
    let rank = -1;
    if (digits && t.no.startsWith(digits)) rank = 0;
    else if (digits && t.no.includes(digits)) rank = 1;
    else if (name.includes(q)) rank = 2;
    if (rank >= 0) scored.push({ t, rank });
  }
  scored.sort((a, b) => a.rank - b.rank || a.t.no.localeCompare(b.t.no));
  return scored.slice(0, limit).map((s) => s.t);
}
